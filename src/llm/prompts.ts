/** 5a — Сформулировать DM кандидату из групповой переписки. */
export function generateDM(msgText: string): string {
    return (
        "Напиши короткое личное сообщение (DM) пользователю в Telegram.\n\n" +
        "Контекст: пользователь написал в групповом чате следующее сообщение:\n" +
        `"${msgText}"\n\n` +
        "Требования:\n" +
        "- стиль для формирования сообщения возьми из своей личности\n" +
        "- Персональное, не шаблонное\n" +
        "- Упоминает конкретику из сообщения\n" +
        "- Не рекламное\n" +
        "- До 3 предложений\n" +
        "- На том же языке, что и сообщение пользователя"
    );
}

// ─── monitor ────────────────────────────────────────────────────────────────

/** 5.4 — Ответ в новом треде (первый ответ пользователя на реплику агента). */
export function generateThreadReply(firstMsg: string, firstReply: string, dialogLines: string): string {
    return (
        "Ты ведёшь диалог в групповом чате Telegram.\n\n" +
        "История переписки:\n" +
        `- Пользователь: ${firstMsg}\n` +
        `- Ты: ${firstReply}\n` +
        `${dialogLines}\n\n` +
        "Напиши ответ, продолжающий диалог естественно. До 3 предложений."
    );
}

/** 5.5 — Ответ в продолжающемся треде (история + новые сообщения). */
export function generateThreadContinuation(historyLines: string, newLines: string): string {
    return (
        "Ты ведёшь диалог в групповом чате Telegram.\n\n" +
        "История переписки:\n" +
        `${historyLines}\n\n` +
        "Новые сообщения:\n" +
        `${newLines}\n\n` +
        "Напиши один ответ, продолжающий диалог естественно. До 3 предложений."
    );
}

/** 5.6.1 / warmup 5 — Темы обсуждения (текст). `messages` — уже отформатированный список. */
export function extractTopics(messages: string): string {
    return (
        "Перечисли основные темы обсуждения в этих сообщениях.\n" +
        "Ответь кратко — список тем без пояснений.\n\n" +
        "Сообщения:\n" +
        messages
    );
}

/** 5.6.2 — Выбор релевантных сообщений (JSON-массив). `messages` — отформатированный список. */
export function selectRelevantMessage(messages: string): string {
    return (
        "Из списка ниже выбери ОДНО сообщение, на которое тебе есть что ответить\n" +
        "исходя из своей личности и экспертизы. Выбери самое подходящее.\n\n" +
        "Верни ТОЛЬКО JSON-массив:\n" +
        '[{ "id": <message_id>, "text": "<текст сообщения>" }]\n\n' +
        "Если подходящих сообщений нет — верни пустой массив [].\n\n" +
        "Сообщения:\n" +
        messages
    );
}

/** 5.6.3 — Ответ на общее сообщение группы. */
export function generateReply(msgText: string): string {
    return (
        "Напиши ответ на следующее сообщение в групповом чате Telegram.\n\n" +
        `Сообщение: "${msgText}"`
    );
}

/** 5.8 — Скоринг сообщения как DM-кандидата (JSON `{ score, reason }`). */
export function scoreForDM(msgText: string, fromName: string): string {
    return (
        "Оцени следующее сообщение по шкале 0.0–1.0 с точки зрения потенциального интереса\n" +
        'для личного обращения (DM). Верни JSON: { "score": <число>, "reason": "<краткое обоснование>" }\n\n' +
        "Учти, чтобы сообщение попало под критерии в нем должна быть деталь/содержание, за что можно зацепиться и уточнить вопросом. Также если сообщение - это короткая реакция, то оно не подходит.\n\n" +
        "Критерии:\n" +
        "- 0.9–1.0: явный запрос помощи / вопрос по теме или конкретно тебе, активная вовлечённость. Если вопрос обращен другому человеку, пропусти\n" +
        "- 0.6–0.8: релевантный контекст, потенциальный интерес по твоей теме, открытый для диалога\n" +
        "- ниже 0.6: ннерелевантно, агрессия, офф-топик, рекламное сообщение, короткая абстрактная реакция, общее пожелание без конкретики, эмоциональная оценка без предмета обсуждения, реплика без самостоятельного смысла — пропустить\n\n" +
        `Сообщение: "${msgText}"\n` +
        `Автор: ${fromName}`
    );
}

/**
 * 5.6 (консолидированный) — один структурированный вызов на канал: выбор не
 * более одного сообщения для ответа + скоринг DM-кандидатов. Заменяет связку
 * `extractTopics` + `selectRelevantMessage` + N×`scoreForDM`. `messages` — уже
 * отформатированный список (по строке на сообщение, с `id=`).
 */
export function analyzeChannelMessages(messages: string): string {
    return (
        "Проанализируй сообщения из группового чата Telegram и выполни две задачи.\n\n" +
        "ЗАДАЧА 1 — Выбери ОДНО сообщение, на которое тебе есть что ответить исходя\n" +
        "из своей личности и экспертизы (самое подходящее). Если подходящего нет —\n" +
        "верни null.\n\n" +
        "ЗАДАЧА 2 — Оцени каждое сообщение по шкале 0.0–1.0 как потенциального\n" +
        "DM-кандидата (интерес для личного обращения). Учти, что для попадания под\n" +
        "критерии в сообщении должна быть деталь/содержание, за что можно зацепиться\n" +
        "и уточнить вопросом. Короткая реакция не подходит.\n" +
        "Критерии:\n" +
        "- 0.9–1.0: явный запрос помощи / вопрос по теме или конкретно тебе, активная вовлечённость. Если вопрос обращен другому человеку, занизь оценку\n" +
        "- 0.6–0.8: релевантный контекст, потенциальный интерес по твоей теме, открытый для диалога\n" +
        "- ниже 0.6: нерелевантно, агрессия, офф-топик, рекламное сообщение, короткая абстрактная реакция, общее пожелание без конкретики, эмоциональная оценка без предмета обсуждения, реплика без самостоятельного смысла\n\n" +
        "Верни ТОЛЬКО JSON:\n" +
        '{ "ответитьНа": { "id": <message_id>, "текст": "<текст сообщения>" } | null,\n' +
        '  "dmКандидаты": [ { "id": <message_id>, "score": <число>, "reason": "<краткое обоснование>" } ] }\n\n' +
        "Сообщения:\n" +
        messages
    );
}

