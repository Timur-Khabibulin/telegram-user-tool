/**
 * Ниша/тематика канала по совокупности описания и постов (channel-niche.ts,
 * channel-metrics.ts --with-niche). Один короткий ответ на русском, не набор
 * категорий по каждому посту — в отличие от scoreTopicRelevance, не привязан к
 * конкретной заданной теме.
 */
export function classifyNiche(title: string, about: string, posts: string[]): string {
    const postsBlock = posts.length > 0
        ? posts.map((p, i) => `Пост ${i + 1}: ${p.slice(0, 500)}`).join("\n\n")
        : "(постов нет)";
    return (
        "Определи нишу/тематику Telegram-канала по совокупности описания и постов.\n" +
        "Ответь ОДНИМ коротким словом или словосочетанием (2-3 слова), на русском,\n" +
        "например: психология, коучинг, юмор, кино, новости, эзотерика/таро, астрология,\n" +
        "личный блог, бьюти, отношения/дейтинг, родительство, бизнес/карьера, финансы,\n" +
        "путешествия, гейминг, музыка, фитнес, кулинария, реклама/маркетинг, знаменитости/шоубиз,\n" +
        "книги, здоровье, IT/технологии, политика/новости, или другая точная категория, если ни одна не подходит.\n\n" +
        'Верни ТОЛЬКО JSON: { "niche": "<категория>" }\n\n' +
        `Название канала: ${title}\n` +
        `Описание: ${about || "(нет описания)"}\n\n` +
        `${postsBlock}`
    );
}

