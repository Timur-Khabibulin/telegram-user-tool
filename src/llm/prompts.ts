/**
 * 4.2+4.3 (консолидированный) — один вызов на тред: тональность последнего
 * сообщения + готовый ответ с полным контекстом. При `negative` поле `ответ`
 * пустое (ответ не генерируется). Заменяет связку `analyzeSentiment` +
 * `generateDmReply`.
 */
export function analyzeAndReply(triggerMessage: string, historyLines: string, newLines: string): string {
    return (
        "Ты ведёшь личную переписку в Telegram. Сделай две вещи за один ответ.\n\n" +
        "ШАГ 1 — Оцени тональность последних сообщений пользователя:\n" +
        "- positive — интерес, вопрос, согласие, продолжение разговора (включая нейтральное)\n" +
        '- negative — агрессия, просьба не писать, оскорбления, "спам", "отпишись"\n\n' +
        "ШАГ 2 — Если тональность positive, напиши ответ. Если negative — ответ НЕ пиши\n" +
        "(оставь поле `ответ` пустым/null).\n\n" +
        "Контекст — пользователь написал в групповом чате:\n" +
        `"${triggerMessage}"\n\n` +
        "История переписки (от старых к новым):\n" +
        `${historyLines}\n\n` +
        "Новые сообщения пользователя:\n" +
        `${newLines}\n\n` +
        "Требования к ответу (только при positive):\n" +
        "- Продолжи диалог естественно, учитывая всю историю\n" +
        "- Стиль возьми из своей личности\n" +
        "- Задай уточняющий вопрос или опиши свой опыт\n" +
        "- До 3 предложений, на языке пользователя\n\n" +
        "Верни ТОЛЬКО JSON:\n" +
        '{ "sentiment": "positive" | "negative", "ответ": "<текст ответа>" | null }'
    );
}

